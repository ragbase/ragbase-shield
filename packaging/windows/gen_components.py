"""Generate Components.wxs (WiX 4, 5 or 6) from a staged Windows payload (packaging/DESIGN.md section 7.1, M5).

Usage:
  python -I packaging/windows/gen_components.py <staged_payload> <out.wxs>

One <Component> per payload folder, as per-user components under the user profile need (ICE38, ICE64):
- Guid = uuid5(shield_ns, "component:" + folder) (stable across builds and versions);
- KeyPath = an HKCU value under Software\\RAGbase\\Shield\\Components (named after the component);
- <RemoveFolder On="uninstall"/> for the folder;
- for every folder that holds .py files, a "__pycache__" child folder (not shipped: Python writes it at the first
  start) with <RemoveFile Name="*.pyc" On="both"/> and <RemoveFolder On="both"/>, so that an uninstall leaves no
  folder behind and an update leaves no stale bytecode.
The root folder (INSTALLFOLDER) also removes the Software\\RAGbase\\Shield key and the parent "Programs" folder
when it is empty. Identifiers are hashes of the relative path: the same tree gives the same file, byte for byte.
"""
from __future__ import annotations

import hashlib
import json
import sys
import uuid
from pathlib import Path
from xml.sax.saxutils import quoteattr

HERE = Path(__file__).resolve().parent
PINS = json.loads((HERE.parent / "common" / "pins.json").read_text(encoding="utf-8"))
NS = uuid.UUID(PINS["windows"]["shield_ns"])
REG_KEY = r"Software\RAGbase\Shield\Components"


def _h(kind: str, rel: str, n: int = 24) -> str:
    return kind + hashlib.sha256(rel.encode("utf-8")).hexdigest()[:n]


def component_guid(rel: str) -> str:
    return "{" + str(uuid.uuid5(NS, "component:" + rel)).upper() + "}"


def dir_id(rel: str) -> str:
    return "INSTALLFOLDER" if rel == "." else _h("d", rel)


def scan(payload: Path) -> tuple[list[str], dict[str, list[str]]]:
    """(folders sorted, files per folder), relative POSIX paths; refuses names MSI cannot hold."""
    folders, files = ["."], {".": []}
    for p in sorted(payload.rglob("*")):
        rel = p.relative_to(payload).as_posix()
        if not rel.isascii():
            raise SystemExit(f"gen_components: non-ASCII name (the MSI uses code page 1252 names): {rel}")
        if p.is_symlink():
            raise SystemExit(f"gen_components: symbolic link in the payload: {rel}")
        if p.is_dir():
            if p.name == "__pycache__":
                raise SystemExit(f"gen_components: __pycache__ shipped in the payload: {rel}")
            folders.append(rel)
            files.setdefault(rel, [])
        elif p.is_file():
            parent = p.parent.relative_to(payload).as_posix() if p.parent != payload else "."
            files.setdefault(parent, []).append(rel)
    return folders, files


def generate(payload: Path) -> str:
    folders, files = scan(payload)
    children: dict[str, list[str]] = {f: [] for f in folders}
    for f in folders[1:]:
        parent = f.rsplit("/", 1)[0] if "/" in f else "."
        children[parent].append(f)
    has_py = {f for f in folders if any(x.endswith(".py") for x in files.get(f, []))}

    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by packaging/windows/gen_components.py from the staged payload. Do not edit. -->",
           '<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs">',
           "  <Fragment>",
           '    <DirectoryRef Id="INSTALLFOLDER">']

    def tree(folder: str, depth: int) -> None:
        pad = "  " * depth
        if folder in has_py:
            out.append(f'{pad}<Directory Id="{_h("p", folder)}" Name="__pycache__" />')
        for child in children[folder]:
            name = child.rsplit("/", 1)[-1]
            out.append(f"{pad}<Directory Id=\"{dir_id(child)}\" Name={quoteattr(name)}>")
            tree(child, depth + 1)
            out.append(f"{pad}</Directory>")

    tree(".", 3)
    out += ["    </DirectoryRef>", "  </Fragment>", "  <Fragment>", '    <ComponentGroup Id="Payload">']
    for folder in folders:
        cid = _h("c", folder)
        out.append(f'      <Component Id="{cid}" Directory="{dir_id(folder)}" Guid="{component_guid(folder)}">')
        out.append(f'        <RegistryValue Root="HKCU" Key="{REG_KEY}" Name="{cid}" Type="integer" Value="1" '
                   'KeyPath="yes" />')
        out.append(f'        <RemoveFolder Id="{_h("r", folder)}" On="uninstall" />')
        if folder == ".":
            out.append('        <RemoveFolder Id="RemoveProgramsFolder" Directory="ProgramsFolder" On="uninstall" />')
            out.append('        <RemoveRegistryKey Id="RemoveShieldKey" Root="HKCU" Key="Software\\RAGbase\\Shield" '
                       'Action="removeOnUninstall" />')
        if folder in has_py:
            pid = _h("p", folder)
            out.append(f'        <RemoveFile Id="{_h("x", folder)}" Directory="{pid}" Name="*.pyc" On="both" />')
            out.append(f'        <RemoveFolder Id="{_h("q", folder)}" Directory="{pid}" On="both" />')
        for rel in files.get(folder, []):
            src = "$(var.PayloadDir)\\" + rel.replace("/", "\\")
            out.append(f'        <File Id="{_h("f", rel, 30)}" Source={quoteattr(src)} />')
        out.append("      </Component>")
    out += ["    </ComponentGroup>", "  </Fragment>", "</Wix>", ""]
    return "\n".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    payload, dest = Path(argv[0]), Path(argv[1])
    if not (payload / "runtime" / "RAGbase Shield.exe").is_file():
        print(f"gen_components: {payload} is not a Windows payload (runtime\\RAGbase Shield.exe missing)",
              file=sys.stderr)
        return 1
    text = generate(payload)
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(text, encoding="utf-8", newline="\n")
    n_files = text.count("<File ")
    n_comp = text.count("<Component ")
    print(f"gen_components: {n_comp} components, {n_files} files -> {dest}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
