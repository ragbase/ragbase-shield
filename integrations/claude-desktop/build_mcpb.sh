#!/usr/bin/env bash
# Build the RAGbase Shield desktop extension for Claude Desktop (.mcpb, server.type "uv").
#
# Usage (from anywhere):
#   integrations/claude-desktop/build_mcpb.sh            # assemble, lock, validate, pack
#   integrations/claude-desktop/build_mcpb.sh --no-lock  # skip "uv lock" (offline build)
#   integrations/claude-desktop/build_mcpb.sh --smoke    # also start the server once and list its tools
#
# Output: dist/ragbase-shield-<version>.mcpb (dist/ is gitignored).
# Needs: bash, python3 >= 3.11 (or the repo .venv), Node.js (npx), and uv for --smoke / lock.
# The bundle holds: manifest.json, icon.png, pyproject.toml (dependencies only), src/server.py
# (launcher) and src/ragbase_shield (a copy of the package). Claude Desktop installs the
# dependencies with uv on the user's machine, so the bundle stays small (no venv inside).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
DO_LOCK=1
DO_SMOKE=0
for arg in "$@"; do
  case "$arg" in
    --no-lock) DO_LOCK=0 ;;
    --smoke) DO_SMOKE=1 ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) echo "Unknown option: $arg" >&2; exit 2 ;;
  esac
done

# A Python with tomllib (3.11+) to read pyproject.toml.
PY=""
for cand in "$ROOT/.venv/bin/python" "$ROOT/.venv/Scripts/python.exe" python3 python; do
  if command -v "$cand" >/dev/null 2>&1 && "$cand" -c 'import tomllib' >/dev/null 2>&1; then
    PY="$cand"; break
  fi
done
if [ -z "$PY" ]; then
  echo "Need Python 3.11+ (tomllib) to read pyproject.toml." >&2; exit 1
fi

BUILD="$ROOT/dist/mcpb-build/ragbase-shield"
rm -rf "$BUILD"
mkdir -p "$BUILD/src"

# 1. Package code (no caches, no tests).
cp -R "$ROOT/src/ragbase_shield" "$BUILD/src/ragbase_shield"
find "$BUILD/src" \( -name '__pycache__' -o -name '*.pyc' -o -name '.DS_Store' \) -prune -exec rm -rf {} +
cp "$HERE/server.py" "$BUILD/src/server.py"
cp "$HERE/icon.png" "$BUILD/icon.png"
for f in LICENSE NOTICE; do
  [ -f "$ROOT/$f" ] && cp "$ROOT/$f" "$BUILD/$f"
done

# 2. manifest.json (version stamped from pyproject.toml) + bundle pyproject.toml.
VERSION="$("$PY" - "$ROOT" "$HERE" "$BUILD" <<'PYEOF'
import json, sys, tomllib
from pathlib import Path

root, here, build = (Path(p) for p in sys.argv[1:4])
project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))["project"]
version = project["version"]

manifest = json.loads((here / "manifest.json").read_text(encoding="utf-8"))
if manifest.get("version") != version:
    print(f"note: manifest version {manifest.get('version')} -> {version} (from pyproject.toml)", file=sys.stderr)
    manifest["version"] = version
(build / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

deps = "\n".join(f"    {json.dumps(d)}," for d in project["dependencies"])
(build / "pyproject.toml").write_text(
    "# Generated by integrations/claude-desktop/build_mcpb.sh. Dependencies only:\n"
    "# the ragbase_shield package itself is bundled in src/.\n"
    "[project]\n"
    'name = "ragbase-shield-desktop-extension"\n'
    f'version = "{version}"\n'
    'description = "RAGbase Shield desktop extension for Claude Desktop"\n'
    f'requires-python = "{project["requires-python"]}"\n'
    f"dependencies = [\n{deps}\n]\n\n"
    "[tool.uv]\n"
    "package = false\n",
    encoding="utf-8",
)
print(version)
PYEOF
)"

cat > "$BUILD/.mcpbignore" <<'EOF'
.venv/
__pycache__/
*.pyc
.pytest_cache/
.DS_Store
server/lib/
server/venv/
EOF

# 3. Optional lock file, so every install resolves the same dependency versions.
if [ "$DO_LOCK" = 1 ]; then
  if command -v uv >/dev/null 2>&1; then
    if ! (cd "$BUILD" && uv lock --quiet); then
      echo "warning: 'uv lock' failed (offline?). The bundle ships without uv.lock." >&2
      rm -f "$BUILD/uv.lock"
    fi
  else
    echo "warning: uv not found, the bundle ships without uv.lock." >&2
  fi
fi

# 4. Optional smoke test: start the server like Claude Desktop does and list its tools.
if [ "$DO_SMOKE" = 1 ]; then
  command -v uv >/dev/null 2>&1 || { echo "--smoke needs uv" >&2; exit 1; }
  "$PY" - "$BUILD" <<'PYEOF'
import json, queue, subprocess, sys, tempfile, threading, time
from pathlib import Path

build = Path(sys.argv[1])
manifest = json.loads((build / "manifest.json").read_text(encoding="utf-8"))
expected = sorted(t["name"] for t in manifest["tools"])
errfile = tempfile.TemporaryFile(mode="w+", encoding="utf-8")
proc = subprocess.Popen(
    ["uv", "run", "--quiet", "--directory", str(build), "src/server.py"],
    stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=errfile, text=True,
)
lines: "queue.Queue[str | None]" = queue.Queue()


def _pump() -> None:
    for raw in proc.stdout:
        lines.put(raw)
    lines.put(None)


threading.Thread(target=_pump, daemon=True).start()


def send(msg: dict) -> None:
    proc.stdin.write(json.dumps(msg) + "\n")
    proc.stdin.flush()


def wait_for(msg_id: int, timeout: float = 300.0):
    """Keep stdin open (a closed stdin stops the server) until the answer with this id arrives."""
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        try:
            raw = lines.get(timeout=max(0.1, end - time.monotonic()))
        except queue.Empty:
            break
        if raw is None:
            break
        try:
            msg = json.loads(raw)
        except ValueError:
            continue
        if msg.get("id") == msg_id:
            return msg
    return None


send({"jsonrpc": "2.0", "id": 1, "method": "initialize", "params": {
    "protocolVersion": "2025-06-18", "capabilities": {},
    "clientInfo": {"name": "build_mcpb-smoke", "version": "0"}}})
tools = None
if wait_for(1) is not None:
    send({"jsonrpc": "2.0", "method": "notifications/initialized"})
    send({"jsonrpc": "2.0", "id": 2, "method": "tools/list"})
    answer = wait_for(2)
    if answer and "result" in answer:
        tools = sorted(t["name"] for t in answer["result"]["tools"])
proc.stdin.close()
try:
    proc.wait(timeout=30)
except subprocess.TimeoutExpired:
    proc.kill()
    proc.wait()
errfile.seek(0)
err = errfile.read()
if tools is None:
    print("smoke: the server did not answer tools/list", file=sys.stderr)
    print(err[-2000:], file=sys.stderr)
    sys.exit(1)
if tools != expected:
    print(f"smoke: tools differ from manifest.json\n  server:   {tools}\n  manifest: {expected}", file=sys.stderr)
    sys.exit(1)
print(f"smoke: OK, {len(tools)} tools: {', '.join(tools)}")
PYEOF
fi

# 5. Validate and pack with the official MCPB CLI.
mkdir -p "$ROOT/dist"
OUT="$ROOT/dist/ragbase-shield-$VERSION.mcpb"
rm -f "$OUT"
npx -y @anthropic-ai/mcpb validate "$BUILD/manifest.json"
npx -y @anthropic-ai/mcpb pack "$BUILD" "$OUT"
echo "Built $OUT"
